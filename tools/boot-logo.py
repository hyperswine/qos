#!/usr/bin/env python3
"""Compile the simple QOS SVG strokes into the dependency-free boot renderer.

The authoritative SVG uses circles and round-capped/joined polylines only.
Run with --check in validation; no raster image or SVG library is needed.
"""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/qos-boot-logo.svg'
OUTPUT = ROOT / 'hal/unix/boot_logo_data.h'


def generate():
    root = ET.parse(SOURCE).getroot()
    if root.attrib['viewBox'] != '0 0 256 96':
        raise ValueError('unexpected logo viewBox')
    lines = ['/* Generated by tools/boot-logo.py from assets/qos-boot-logo.svg. */',
             '#ifndef QOS_BOOT_LOGO_DATA_H', '#define QOS_BOOT_LOGO_DATA_H',
             'typedef struct { float x, y, radius; } qos_logo_point;',
             'typedef struct { unsigned color; float width; int count; const qos_logo_point *points; } qos_logo_stroke;']
    strokes = []
    group = root.find('{*}g')
    for i, element in enumerate(group):
        attrs = dict(group.attrib, **element.attrib)
        if attrs.get('fill') != 'none' or attrs.get('stroke-linecap') != 'round' or attrs.get('stroke-linejoin') != 'round':
            raise ValueError('only unfilled round strokes are supported')
        color = attrs['stroke']
        if len(color) != 7 or color[0] != '#':
            raise ValueError('expected RGB hex color')
        int(color[1:], 16)
        width = float(attrs['stroke-width'])
        if element.tag.endswith('circle'):
            points = [(float(attrs['cx']), float(attrs['cy']), float(attrs['r']))]
        elif element.tag.endswith('polyline'):
            points = [(*map(float, point.split(',')), 0.0) for point in attrs['points'].split()]
            if len(points) < 2:
                raise ValueError('polyline needs at least two points')
        else:
            raise ValueError('unsupported SVG element')
        values = ', '.join('{' + ', '.join(f'{v:.6f}f' for v in p) + '}' for p in points)
        lines.append(f'static const qos_logo_point qos_logo_points_{i}[] = {{{values}}};')
        strokes.append(f'  {{0x{color[1:]}, {width:.6f}f, {len(points)}, qos_logo_points_{i}}}')
    lines += ['static const qos_logo_stroke qos_logo_strokes[] = {', ',\n'.join(strokes), '};', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit('boot logo header is stale; run python3 tools/boot-logo.py')
        print('Boot logo: SVG and renderer data agree')
    else:
        OUTPUT.write_text(generated)
